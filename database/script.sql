-- Script de criação do banco - Sistema de Controle de Estoque
-- Banco: PostgreSQL
--
-- Como usar:
--   1) Criar o banco (uma vez):   CREATE DATABASE estoque;
--   2) Conectar no banco estoque e executar este script.

-- Tabela de mercadorias
CREATE TABLE IF NOT EXISTS mercadorias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(255) NOT NULL,
    descricao  VARCHAR(255),
    preco      NUMERIC(38, 2) NOT NULL
);

-- Tabela de estoques (cada registro pertence a uma mercadoria)
CREATE TABLE IF NOT EXISTS estoques (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade         NUMERIC(38, 2) NOT NULL,
    quantidade_minima  NUMERIC(38, 2),
    quantidade_maxima  NUMERIC(38, 2),
    localizacao        VARCHAR(255),
    mercadoria_id      BIGINT NOT NULL,
    CONSTRAINT fk_estoques_mercadoria
        FOREIGN KEY (mercadoria_id) REFERENCES mercadorias (id)
);

